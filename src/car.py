class Car:
    def __init__(
        self, number, name, phone, model, color, parking, resident, park_in, park_out
    ):
        self.number = number
        self.name = name
        self.phone = phone
        self.model = model
        self.color = color
        self.parking = parking
        self.resident = resident
        self.park_in = park_in
        self.park_out = park_out
